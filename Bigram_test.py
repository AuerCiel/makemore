#（4）上面说了我们希望做一个什么样的神经网络。这里我们需要处理一下输入
#       1.前面学的micrograd的MLP，只能接受一串数字。也就是Tensor张量。我们需要把二元组字符变成一串向量
#       2.所以我们这里把字符通过字典变成数字，然后采用one-hot编码。
#       3.比如b的key是2，那么传入神经网络的就是：一个27位的数组，下标为2的元素值为1，别的地方都是0
#       4.假设我们上面的循环最终得到的向量xs和ys长度最终是：n。
#       5.下面方法实际就是：把每一个xs和ys的分量，扩展成一个长度为27的一维数组
xs_one_hot = torch.nn.functional.one_hot(xs,num_classes=27).float()
ys_one_hot = torch.nn.functional.one_hot(ys,num_classes=27).float()



#创建一个名为 W 的 PyTorch 张量，形状为 27 行 27 列，元素是随机数。
#randn函数生成的随机数服从标准正态分布
#（5）为什么这里的生成的W参数矩阵规格要求是27*27？
#       1.前面经过热位编码之后，xs的数据变成了这样：总长度为n，每一个元素都是长度为27的Tensor
#       2.这行生成的随机数矩阵也是：27*27个随机数
#       3.因为输入层有27个神经元，理论上来说，这一层神经元，每一个有多少个输出端，第二层就应该有多少个神经元
#       4.比如第二层有5个神经元，那么第一层的每一个神经元就应该有五个输出。每一个输出都有一个参数w
#       5.那么这种情况就应该是27*5个参数作为随机数
W = torch.randn((27,27), requires_grad=True)

#将对应的参数和输入相乘：
first_layer_out = xs_one_hot @ W


#（6）二维Tensor进行矩阵乘法的时候，怎么确定哪个是行哪个是列？
#       1.比如拿上面做例子：假如第二层有5个神经元————因为Andrej取的27*27两个维度一样，不好区分
#       2.那么拿到的xs热位矩阵规格是这样的：
#           第一层有n个元素，每一个元素是长度为27的张量。
#           每一行代表的就是：一个元组对应的输入向量
#       3.拿到的W参数矩阵是这样的：
#           第一层有27个元素，每一个元素是一个长度为5的张量。
#           一列就代表输入层的27个神经元，对于第二层的一个神经元在连接上的参数们w
#       4.我们期望的结果是这样的：
#           得到一个n*5的张量。第一层有n个元素，每一个元素是长度为5的张量
#           含义是：n个输入值代表我们前面读入了n个元组。
#                   长度为5的张量表示，每一个输入的张量，会给第二层每一个神经元带来一个输出，所以一共就是5个
#       5.所以，我们采用行向量的思路来看这次矩阵乘法：
#           行向量：假设C = AB
#           那么：C 的每一行，等于 A 的对应行，与 B 的每一列做点积。
#       6.放到这里来看：
#           结果矩阵的第k行，就是xs热位矩阵的第k行和参数矩阵每一列逐个点乘的结果
#           那么，结果矩阵的第k列就是：某一个输入向量，作为神经网络的输入的时候，第二层五个神经元接收到的输入



#（7）注意到，神经网络的输出值是有可能负的：————这层处理叫做softmax
#       1.我们是这样得到神经网络的输出的：
#           当前神经网络结构是单层的，也就是说，输入的向量，经过一次和参数们的计算，就进入第二层了
#           第二层也就是输出层。
#       2.输入的列向量都是一位热位编码的，经过w的运算，有可能最终输出给第二层的，也就是神经网络输出，会是负数
#       3.我们希望对这些负数做一些处理。把他们映射成正数，然后把这些浮点正数，当做频率处理，计算最终概率分布




#（8）这里的n个二元组，有很多是重复的二元组。
#   1.这里的n大约是22万。但是二元组种类只有27*27种。所以其实神经网络进行了很多次重复运算
#   2.所以得到的probs矩阵，也有很多重复项
