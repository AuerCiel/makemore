#（3）这里实际上做的是：
#       把所有名字拆成二元组。
#       然后根据二元组的字符内容和先前定义的字典stoi，把字符二元组变成数字二元组。比如(a,b)--->(1,2)
#       然后二元组的第一个，存入xs数组，第二个存入ys数组。并且把xs和ys数组变成Tensor
#       并且，注意到这样处理的核心性质：同一个下标对应的xs内元素和ys内元素，构成原来的一个二元组
#       而且二元组们显然是允许重复的，毕竟它们出现的频率正是我们要统计的内容。
#       比如遍历words内的名字的时候，可能出现很多次(a,b)。

xs,ys = [],[]

for w in words:
    chs = ['.'] + list(w) + ['.']
    for ch1, ch2 in zip(chs, chs[1:]):
        ix1 = stoi[ch1]
        ix2 = stoi[ch2]
