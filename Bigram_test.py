num = xs.nelement()#这句话的意思是：计算xs这个张量内部元素数量，然后赋给num
loss = -probs[torch.arange(num), ys].log().mean()
#涉及的语法：
#   torch.arange(num),表示生成的一个大小为num的张量，并且内容是从0到num-1.
#   prob【】二维张量里面传入两个一维张量，是在高级索引：
#       



#（9）进行梯度下降：
learning_rate = 50.0
print('开始进行梯度下降')

#学习两百次
for k in range(2000):
    
    #这一步进行前向传播
    first_layer_out = xs_one_hot @ W
    counts = first_layer_out.exp()
    probs = counts / counts.sum(1, keepdim=True)
    loss = -probs[torch.arange(num), ys].log().mean()

    #重置grad防止偏差
    W.grad = None
    loss.backward()
    W.data += -learning_rate * W.grad

    #选择性打印Loss函数
    if k % 200 == 0 or k == 1999:
        print(k, loss.item())

